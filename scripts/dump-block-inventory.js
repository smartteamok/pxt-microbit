"use strict";

/**
 * Dump the authoritative block-ID inventory for this target.
 *
 * Sources (see scripts/lib/block-inventory.js):
 *   - API blocks from built/target.json#apiInfo
 *   - Blockly built-ins from pxt-core/built/pxtlib.js
 *
 * Usage:
 *   pxt buildtarget                 # (re)generate built/target.json
 *   node scripts/dump-block-inventory.js            # markdown table to stdout
 *   node scripts/dump-block-inventory.js --json     # JSON to stdout
 *
 * Paste the curated output into docs/smartteam/native-blocks-inventory.md.
 */

const { collectInventory } = require("./lib/block-inventory");

function shortPkg(p) {
    return (p || "").replace(/^libs\//, "");
}

function escapeCell(s) {
    return String(s || "").replace(/\|/g, "\\|").replace(/\n/g, " ").trim();
}

function main() {
    const asJson = process.argv.includes("--json");
    const { apiBlocks, builtinBlocks, allIds } = collectInventory();

    if (asJson) {
        process.stdout.write(JSON.stringify({ apiBlocks, builtinBlocks, count: allIds.size }, null, 2) + "\n");
        return;
    }

    // Course profile packages only re-export their dependencies' blocks, which
    // duplicates every entry. Drop them and dedupe by blockId so each block is
    // listed once under its defining (functional) package.
    const isCourse = pkg => /(^|\/)smartteam-course-\d+$/.test(pkg || "");
    const seen = new Set();
    const dedupApi = apiBlocks
        .filter(b => !isCourse(b.package))
        .filter(b => (seen.has(b.blockId) ? false : seen.add(b.blockId)));

    const lines = [];
    lines.push("# Native + SmartTeam Block Inventory (generated)");
    lines.push("");
    lines.push("Generated by `node scripts/dump-block-inventory.js`. Do not hand-edit the tables;");
    lines.push("re-run after `pxt buildtarget`. Curated notes can go above each section.");
    lines.push("");
    lines.push(`Total distinct block IDs: **${allIds.size}** (API, deduped: ${dedupApi.length}; Blockly built-ins: ${builtinBlocks.length}).`);
    lines.push("");

    // API blocks grouped by package (deduped, course profiles excluded)
    const byPkg = {};
    dedupApi.forEach(b => {
        const k = shortPkg(b.package);
        (byPkg[k] = byPkg[k] || []).push(b);
    });

    lines.push("## API blocks (by package)");
    lines.push("");
    Object.keys(byPkg).sort().forEach(pkg => {
        lines.push(`### ${pkg}`);
        lines.push("");
        lines.push("| blockId | qName | namespace | label |");
        lines.push("|---|---|---|---|");
        byPkg[pkg]
            .sort((a, b) => a.blockId.localeCompare(b.blockId))
            .forEach(b => {
                const ns = b.blockNamespace || b.namespace;
                lines.push(`| \`${b.blockId}\` | ${escapeCell(b.qName)} | ${escapeCell(ns)} | ${escapeCell(b.block)} |`);
            });
        lines.push("");
    });

    // Blockly built-ins grouped by category
    const byCat = {};
    builtinBlocks.forEach(b => {
        (byCat[b.category || "?"] = byCat[b.category || "?"] || []).push(b.blockId);
    });

    lines.push("## Blockly built-ins (by category)");
    lines.push("");
    lines.push("These are NOT in apiInfo. Use these IDs in `toolboxFilter.blocks` / profile allow-lists.");
    lines.push("");
    lines.push("| category | blockId |");
    lines.push("|---|---|");
    Object.keys(byCat).sort().forEach(cat => {
        byCat[cat].sort().forEach(id => lines.push(`| ${cat} | \`${id}\` |`));
    });
    lines.push("");

    process.stdout.write(lines.join("\n"));
}

main();
